package org.grandparents.model;

/**
 * Типы транзакций баллов
 */
public enum TransactionType {

    /**
     * Заработал баллы (за отправку заявки партнёрам)
     */
    EARN,

    /**
     * Потратил баллы (за принятие заявки)
     */
    SPEND,

    /**
     * Бонусные баллы (за 5 закрытых заявок в месяц)
     */
    BONUS,

    /**
     * Начальный бонус (при регистрации пансионата)
     */
    INIT
}